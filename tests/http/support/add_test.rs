//! Filling in and submitting the Add test form the way a browser with
//! JavaScript off does: one multipart post with the form's fields in
//! document order (the CSRF token first, the dropdowns and their **+ New
//! value** fields, the files, then the pressed button). With JavaScript the
//! page adds a `kind_{i}` and a `label_{i}` field per file; tests send those
//! with [`AddTestForm::field`].

use futures_util::stream;
use reqwest::multipart::{Form, Part};
use scraper::Selector;

use super::{
    TestApp,
    fixtures::{Month, NewTest},
    html::{Page, text},
};

/// The Add test form, read from the page and being filled in.
pub struct AddTestForm {
    csrf: String,
    /// Each dropdown in order: its name and its options' `(text, value)`.
    selects: Vec<(String, Vec<(String, String)>)>,
    /// The chosen `(dropdown, option value, typed new value)`.
    choices: Vec<(String, String, String)>,
    files: Vec<(String, Body)>,
    fields: Vec<(String, String)>,
}

enum Body {
    Bytes(Vec<u8>),
    /// That many bytes, generated as they are sent rather than held.
    Generated(u64),
}

impl AddTestForm {
    pub fn read(page: &Page) -> Self {
        let form = page.one("form#add-test");
        let csrf = form
            .select(&Selector::parse("input[name=csrf]").unwrap())
            .next()
            .and_then(|input| input.value().attr("value"))
            .expect("a CSRF token in the form")
            .to_owned();
        let option = Selector::parse("option").unwrap();
        let selects = form
            .select(&Selector::parse("select[name]").unwrap())
            .map(|select| {
                let options = select
                    .select(&option)
                    .map(|o| (text(o), o.value().attr("value").unwrap_or_default().to_owned()))
                    .collect();
                (select.value().attr("name").unwrap().to_owned(), options)
            })
            .collect();
        Self {
            csrf,
            selects,
            choices: Vec::new(),
            files: Vec::new(),
            fields: Vec::new(),
        }
    }

    /// The `(text, value)` options of a dropdown.
    pub fn options(&self, name: &str) -> &[(String, String)] {
        &self
            .selects
            .iter()
            .find(|(n, _)| n == name)
            .unwrap_or_else(|| panic!("the form has no {name} dropdown"))
            .1
    }

    /// Pick the option showing `text` in dropdown `name`, or, when there is
    /// none, pick **+ New value** and type `text`.
    pub fn choose(mut self, name: &str, text: &str) -> Self {
        let (value, typed) = match self.options(name).iter().find(|(t, _)| t == text) {
            Some((_, value)) => (value.clone(), String::new()),
            None => (self.new_value_option(name), text.to_owned()),
        };
        self.choices.retain(|(n, _, _)| n != name);
        self.choices.push((name.to_owned(), value, typed));
        self
    }

    /// Pick **+ New value** in dropdown `name` and type `text`, even if the
    /// dropdown offers it.
    pub fn new_value(mut self, name: &str, text: &str) -> Self {
        let value = self.new_value_option(name);
        self.choices.retain(|(n, _, _)| n != name);
        self.choices.push((name.to_owned(), value, text.to_owned()));
        self
    }

    /// Leave dropdown `name` on "Choose…".
    pub fn unchoose(mut self, name: &str) -> Self {
        self.choices.retain(|(n, _, _)| n != name);
        self
    }

    fn new_value_option(&self, name: &str) -> String {
        self.options(name)
            .iter()
            .find(|(t, _)| t == "+ New value…")
            .unwrap_or_else(|| panic!("the {name} dropdown has no + New value"))
            .1
            .clone()
    }

    /// Choose a Test's six Facet values, typing any the form does not offer.
    pub fn test(self, test: &NewTest) -> Self {
        let or_unknown = |value: Option<&str>| value.unwrap_or("Unknown").to_owned();
        let month = match test.month {
            Month::Known(name) => name,
            Month::Unknown => "Unknown",
            Month::NotApplicable => "Not applicable",
        };
        self.choose("year", &test.year.map_or("Unknown".to_owned(), |y| y.to_string()))
            .choose("month", month)
            .choose("competition", &or_unknown(test.competition))
            .choose("division_level", &or_unknown(test.division_level))
            .choose("test_type", &or_unknown(test.test_type))
            .choose("host", &or_unknown(test.host))
    }

    /// Add a file to the file input.
    pub fn file(mut self, name: &str, bytes: &[u8]) -> Self {
        self.files.push((name.to_owned(), Body::Bytes(bytes.to_vec())));
        self
    }

    /// Add a file of `len` generated bytes, streamed as it is sent.
    pub fn generated_file(mut self, name: &str, len: u64) -> Self {
        self.files.push((name.to_owned(), Body::Generated(len)));
        self
    }

    /// Send a field after the files, as the hydrated page's per-file kind
    /// and label fields are.
    pub fn field(mut self, name: &str, value: &str) -> Self {
        self.fields.push((name.to_owned(), value.to_owned()));
        self
    }

    /// The multipart body a browser would send after pressing the button
    /// whose value is `save`. A dropdown left on "Choose…" (a disabled
    /// option) sends nothing.
    fn multipart(self, save: &str) -> Form {
        let mut form = Form::new().text("csrf", self.csrf);
        for (name, _) in &self.selects {
            let chosen = self.choices.iter().find(|(n, _, _)| n == name);
            if let Some((_, value, _)) = chosen {
                form = form.text(name.clone(), value.clone());
            }
            let typed = chosen.map(|(_, _, typed)| typed.clone()).unwrap_or_default();
            form = form.text(format!("{name}_new"), typed);
        }
        if self.files.is_empty() {
            form = form.part("files", Part::bytes(Vec::new()).file_name(""));
        }
        for (name, body) in self.files {
            let part = match body {
                Body::Bytes(bytes) => Part::bytes(bytes),
                Body::Generated(len) => Part::stream_with_length(generated(len), len),
            };
            form = form.part(
                "files",
                part.file_name(name).mime_str("application/octet-stream").unwrap(),
            );
        }
        for (name, value) in self.fields {
            form = form.text(name, value);
        }
        form.text("save", save.to_owned())
    }
}

/// `len` bytes of a repeating pattern, produced a MiB at a time.
fn generated(len: u64) -> reqwest::Body {
    const CHUNK: u64 = 1024 * 1024;
    let chunks = len.div_ceil(CHUNK);
    reqwest::Body::wrap_stream(stream::iter((0..chunks).map(move |i| {
        let size = CHUNK.min(len - i * CHUNK) as usize;
        Ok::<_, std::io::Error>((0..size).map(|b| (b % 251) as u8).collect::<Vec<u8>>())
    })))
}

/// One Document as the page lists it after saving.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SavedDocument {
    pub id: i64,
    pub kind: String,
    pub label: Option<String>,
    /// e.g. "PDF supplied", "PDF being prepared"
    pub pdf_status: String,
    /// "Published" or "Hidden"
    pub visibility: String,
    /// e.g. "labels by an Admin"
    pub label_source: String,
}

impl TestApp {
    /// The Add test form as an Admin sees it.
    pub async fn add_test_form(&self, cookie: &str) -> AddTestForm {
        AddTestForm::read(&self.get_page_as("/admin/tests/new", Some(cookie)).await)
    }

    /// Submit the Add test form by pressing **Save hidden** (`"hidden"`) or
    /// **Publish** (`"publish"`).
    pub async fn submit_add_test(&self, cookie: &str, form: AddTestForm, save: &str) -> reqwest::Response {
        self.http
            .post(self.url("/api/admin/tests"))
            .header("origin", &self.base_url)
            .header("cookie", cookie)
            .multipart(form.multipart(save))
            .send()
            .await
            .expect("POST the Add test form")
    }

    /// Submit the Add test form, expecting it saved, and return the new (or
    /// added-to) Test's ID.
    pub async fn add_test(&self, cookie: &str, form: AddTestForm, save: &str) -> i64 {
        let response = self.submit_add_test(cookie, form, save).await;
        let status = response.status();
        let location = response
            .headers()
            .get("location")
            .map(|l| l.to_str().unwrap().to_owned())
            .unwrap_or_default();
        assert_eq!(status, 303, "Add test: {}", response.text().await.unwrap_or_default());
        added_test(&location)
    }

    /// The Documents the page lists after saving, in ID (upload) order.
    pub async fn saved_documents(&self, cookie: &str, test: i64) -> Vec<SavedDocument> {
        let page = self
            .get_page_as(&format!("/admin/tests/new?added={test}"), Some(cookie))
            .await;
        page.select("#added li.document")
            .into_iter()
            .map(|li| {
                let part = |css: &str| li.select(&Selector::parse(css).unwrap()).next().map(text);
                SavedDocument {
                    id: li.value().attr("id").unwrap().trim_start_matches('D').parse().unwrap(),
                    kind: part(".kind").unwrap(),
                    label: part(".label"),
                    pdf_status: part(".pdf-status").unwrap(),
                    visibility: part(".visibility").unwrap(),
                    label_source: part(".label-source").unwrap(),
                }
            })
            .collect()
    }

    /// The kinds of the Documents the page lists after saving.
    pub async fn saved_kinds(&self, cookie: &str, test: i64) -> Vec<String> {
        self.saved_documents(cookie, test)
            .await
            .into_iter()
            .map(|d| d.kind)
            .collect()
    }

    /// Every change log entry, oldest first, as `(entity, entity id, field,
    /// before, after)`, read from the table: the log's contract with the
    /// Change log page (`tests/http/change_log.rs` checks the page itself).
    pub async fn change_log(&self) -> Vec<(String, i64, String, Option<String>, Option<String>)> {
        sqlx::query_as("SELECT entity, entity_id, field, before, after FROM change_log ORDER BY id")
            .fetch_all(&self.db)
            .await
            .expect("read the change log")
    }

    /// The keys of every object this test stored, without the test's prefix.
    pub async fn stored_keys(&self) -> Vec<String> {
        let mut keys = Vec::new();
        let mut pages = self
            .s3
            .list_objects_v2()
            .bucket(&self.bucket)
            .prefix(&self.key_prefix)
            .into_paginator()
            .send();
        while let Some(page) = pages.next().await {
            for object in page.expect("list objects").contents() {
                keys.push(object.key().unwrap().trim_start_matches(&self.key_prefix).to_owned());
            }
        }
        keys.sort();
        keys
    }
}

/// The Test ID in a `/admin/tests/new?added={id}` redirect.
pub fn added_test(location: &str) -> i64 {
    let query = location
        .strip_prefix("/admin/tests/new?")
        .unwrap_or_else(|| panic!("redirected to {location:?}, not the Add test page"));
    query
        .split('&')
        .find_map(|pair| pair.strip_prefix("added="))
        .unwrap_or_else(|| panic!("redirected to {location:?}, not a saved Test"))
        .parse()
        .unwrap()
}
