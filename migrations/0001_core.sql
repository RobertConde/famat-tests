-- ---------------------------------------------------------------- Documents

CREATE TYPE label_source AS ENUM ('sheet', 'ai', 'admin');

CREATE TYPE pdf_status AS ENUM ('preparing', 'ready', 'failed', 'not_convertible');

CREATE TABLE documents (
    -- Migrated Documents keep their legacy tid.
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind_id               bigint NOT NULL REFERENCES document_kinds (id),
    -- Optional short label telling two Documents of one kind apart ("Part 2").
    label                 text CHECK (label IS NULL OR btrim(label) <> ''),
    published             boolean NOT NULL DEFAULT false,
    needs_review          boolean NOT NULL DEFAULT false,
    needs_review_comment  text,
    label_source          label_source NOT NULL DEFAULT 'admin',
    -- e.g. "duplicate of 1234"
    note                  text,
    pdf_status            pdf_status NOT NULL DEFAULT 'preparing',
    trashed_at            timestamptz,
    created_at            timestamptz NOT NULL DEFAULT now(),
    updated_at            timestamptz NOT NULL DEFAULT now()
);

-- A Document belongs to one or more Tests (Master Keys, multi-Division
-- answer files).
CREATE TABLE test_documents (
    test_id     bigint NOT NULL REFERENCES tests (id) ON DELETE CASCADE,
    document_id bigint NOT NULL REFERENCES documents (id) ON DELETE CASCADE,
    PRIMARY KEY (test_id, document_id)
);
CREATE INDEX test_documents_document_id ON test_documents (document_id);

-- The files stored in Garage for a Document: one Original and at most one
-- PDF made from it. An Original that is a PDF is its own PDF and has no
-- 'pdf' row. The object key is derived, never stored: documents/{id}/{role}.
CREATE TYPE file_role AS ENUM ('original', 'pdf');

CREATE TABLE document_files (
    document_id  bigint    NOT NULL REFERENCES documents (id) ON DELETE CASCADE,
    role         file_role NOT NULL,
    content_type text      NOT NULL,
    -- Without the dot, lower case: "pdf", "docx". Empty when the file had none.
    extension    text      NOT NULL CHECK (extension = lower(extension)),
    byte_size    bigint    NOT NULL CHECK (byte_size >= 0),
    sha256       bytea     NOT NULL CHECK (length(sha256) = 32),
    created_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (document_id, role)
);
