-- The core of the archive: Tests, their Facet values, Documents and Document
-- kinds. Vocabulary follows GLOSSARY.md.
--
-- Room for the future question bank (not built in v1): a Question will
-- reference documents(id) plus a page number; Attachments, Question groups
-- and Dependencies hang off Questions. Garage keys are namespaced by entity
-- ("documents/{id}/{role}"), so Attachments get their own namespace. None of
-- that needs a change to the tables below.

-- ------------------------------------------------------------ Facet values

-- The Facets with an Admin-curated value list. Year is a plain number on the
-- Test and has no list.
CREATE TYPE facet AS ENUM ('month', 'competition', 'division_level', 'test_type', 'host');

CREATE TABLE facet_values (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facet         facet   NOT NULL,
    name          text    NOT NULL CHECK (btrim(name) <> ''),
    -- Lower sorts first in dropdowns and results. Not unique, so reordering
    -- can rewrite a whole Facet without juggling constraints; ties sort by name.
    display_order integer NOT NULL,
    UNIQUE (facet, id),
    UNIQUE (facet, name)
);

-- Former names kept on rename or merge, so old links and searches still work.
CREATE TABLE facet_value_aliases (
    facet          facet  NOT NULL,
    alias          text   NOT NULL,
    facet_value_id bigint NOT NULL,
    PRIMARY KEY (facet, alias),
    FOREIGN KEY (facet, facet_value_id) REFERENCES facet_values (facet, id) ON DELETE CASCADE
);

-- -------------------------------------------------------------------- Tests

CREATE TABLE tests (
    -- Migrated Tests keep their legacy test_id; the import moves the sequence
    -- past the maximum afterwards.
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- The six Facets. NULL means unknown.
    year                  smallint CHECK (year BETWEEN 1900 AND 2100),
    month_id              bigint,
    -- Month is not applicable for State, National and Mail-in, which is
    -- different from unknown: unknown is (month_applicable AND month_id IS NULL).
    month_applicable      boolean NOT NULL DEFAULT true,
    competition_id        bigint,
    division_level_id     bigint,
    test_type_id          bigint,
    host_id               bigint,

    published             boolean NOT NULL DEFAULT false,
    needs_review          boolean NOT NULL DEFAULT false,
    needs_review_comment  text,
    trashed_at            timestamptz,
    created_at            timestamptz NOT NULL DEFAULT now(),
    updated_at            timestamptz NOT NULL DEFAULT now(),

    CHECK (month_applicable OR month_id IS NULL),

    -- Each Facet column may only point at a value of its own Facet.
    month_facet           facet GENERATED ALWAYS AS ('month') STORED,
    competition_facet     facet GENERATED ALWAYS AS ('competition') STORED,
    division_level_facet  facet GENERATED ALWAYS AS ('division_level') STORED,
    test_type_facet       facet GENERATED ALWAYS AS ('test_type') STORED,
    host_facet            facet GENERATED ALWAYS AS ('host') STORED,
    FOREIGN KEY (month_facet, month_id) REFERENCES facet_values (facet, id),
    FOREIGN KEY (competition_facet, competition_id) REFERENCES facet_values (facet, id),
    FOREIGN KEY (division_level_facet, division_level_id) REFERENCES facet_values (facet, id),
    FOREIGN KEY (test_type_facet, test_type_id) REFERENCES facet_values (facet, id),
    FOREIGN KEY (host_facet, host_id) REFERENCES facet_values (facet, id)
);

-- ----------------------------------------------------------- Document kinds

CREATE TABLE document_kinds (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                text    NOT NULL UNIQUE CHECK (btrim(name) <> ''),
    display_order       integer NOT NULL,
    -- What a Document of this kind contains; the Includes filters derive
    -- from these, aggregated over a Test's Documents.
    contains_questions  boolean NOT NULL DEFAULT false,
    contains_answers    boolean NOT NULL DEFAULT false,
    contains_solutions  boolean NOT NULL DEFAULT false
);

